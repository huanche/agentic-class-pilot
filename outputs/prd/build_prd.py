            tcpr.append(margins)
            shade=OxmlElement('w:shd'); shade.set(qn('w:fill'),'E8EEF5' if ri==0 else ('F7F9FC' if ri%2==0 else 'FFFFFF')); tcpr.append(shade)
            for para in c.paragraphs:
                para.paragraph_format.space_after=Pt(3); para.paragraph_format.space_before=Pt(3); para.paragraph_format.line_spacing=1.12
